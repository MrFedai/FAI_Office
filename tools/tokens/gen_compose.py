"""Generates the Compose design tokens from the kit tokens plus the FAI Office additions.

    python3 tools/tokens/gen_compose.py          write app/.../theme/FaiTokens.kt and print a summary
    python3 tools/tokens/gen_compose.py --check  exit 1 (with the difference) when the committed file is out of date

Inputs: design/tokens/fai.tokens.json (verbatim copy of the shared kit) and design/tokens/office.tokens.json
(drops, renames, additions). Python 3 standard library only.
"""

import difflib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
KIT = ROOT / "design/tokens/fai.tokens.json"
OFFICE = ROOT / "design/tokens/office.tokens.json"
OUT = ROOT / "app/src/commonMain/kotlin/org/faioffice/app/theme/FaiTokens.kt"

HEADER = """/* This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0. If a copy of the MPL was
 * not distributed with this file, You can obtain one at https://mozilla.org/MPL/2.0/. */
"""
WEIGHTS = {400: "Normal", 500: "Medium", 600: "SemiBold", 700: "Bold"}
I4, I8, I12 = " " * 4, " " * 8, " " * 12


def parse_colour(value):
    """'#RRGGBB' or 'rgba(r,g,b,a)' -> (a, r, g, b) as 0..255 ints."""
    if re.fullmatch(r"#[0-9A-Fa-f]{6}", value):
        return 255, int(value[1:3], 16), int(value[3:5], 16), int(value[5:7], 16)
    m = re.fullmatch(r"rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([0-9.]+)\s*\)", value)
    if not m:
        sys.exit(f"!! unknown colour value: {value}")
    r, g, b, a = int(m[1]), int(m[2]), int(m[3]), float(m[4])
    return round(a * 255), r, g, b


def kotlin_colour(argb):
    return "Color(0x%02X%02X%02X%02X)" % argb


def merge_colours(kit, office, theme):
    dropped = set(office["drop"]["color"])
    raw = {k: v for k, v in kit["color"][theme].items() if k not in dropped}
    raw.update(office["color"][theme])
    out = {}
    for name, value in raw.items():
        if not value.startswith(("#", "rgba")):
            value = raw[value]  # alias such as "fileConverter": "violet"
        out[name] = parse_colour(value)
    return out


def breakpoint_min(spec):
    """'900-1279' / '1280+' / 780 -> lower bound in dp."""
    return int(str(spec).split("-")[0].rstrip("+"))


def luminance(argb):
    def channel(c):
        c /= 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    _, r, g, b = argb
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def over(top, bottom):
    a = top[0] / 255
    return (255,) + tuple(round(t * a + b * (1 - a)) for t, b in zip(top[1:], bottom[1:]))


def ratio(fg, bg):
    hi, lo = sorted((luminance(fg), luminance(bg)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def contrast_pairs(colours, contrast):
    """Every (label, ratio) the Kotlin ContrastTest also checks."""
    for text in contrast["text"]:
        for surface in contrast["surfaces"]:
            yield f"{text} on {surface}", ratio(colours[text], colours[surface])
    for text, fill in contrast["onFill"].items():
        yield f"{text} on {fill}", ratio(colours[text], colours[fill])
    for text, tint in contrast["onTint"].items():
        for surface in contrast["surfaces"]:
            yield f"{text} on {tint}/{surface}", ratio(colours[text], over(colours[tint], colours[surface]))


def kt_map(name, kdoc, entries, value_type):
    lines = [f"{I4}/** {kdoc} */", f"{I4}val {name}: Map<String, {value_type}> =", f"{I8}mapOf("]
    lines += [f'{I12}"{key}" to {value},' for key, value in entries]
    lines.append(f"{I8})")
    return lines


def kt_object(name, kdoc, entries):
    lines = [f"/** {kdoc} */", f"object {name} {{"]
    lines += [f"{I4}{entry}" for entry in entries]
    lines += ["}", ""]
    return lines


def generate(kit, office):
    themes = {t: merge_colours(kit, office, t) for t in ("dark", "light")}
    names = list(themes["dark"])
    if names != list(themes["light"]):
        sys.exit("!! dark and light themes must define the same colours in the same order")
    contrast = office["contrast"]
    file_kinds = [n for n in names if n.startswith("file")]

    out = [HEADER]
    out += [
        f"// Generated by tools/tokens/gen_compose.py from design/tokens/fai.tokens.json (kit {kit['meta']['version']})",
        f"// and design/tokens/office.tokens.json ({office['meta']['version']}). Do not edit by hand: change the json,",
        "// then run the script (ci/lint.sh fails when this file is out of date).",
        '@file:Suppress("MagicNumber", "LongParameterList")',
        "",
        "package org.faioffice.app.theme",
        "",
        "import androidx.compose.animation.core.CubicBezierEasing",
        "import androidx.compose.runtime.Immutable",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.text.TextStyle",
        "import androidx.compose.ui.text.font.FontFamily",
        "import androidx.compose.ui.text.font.FontWeight",
        "import androidx.compose.ui.unit.dp",
        "import androidx.compose.ui.unit.sp",
        "",
        "/** Colour tokens of one theme ([FaiPalette.dark], [FaiPalette.light]). */",
        "@Immutable",
        "class FaiColors(",
    ]
    out += [f"{I4}val {n}: Color," for n in names]
    out.append(") {")
    out += kt_map(
        "fileTypes",
        "File-type meaning colours by kind; always shown with the type's name or extension.",
        [(n[4].lower() + n[5:], n) for n in file_kinds],
        "Color",
    )
    out.append("")
    out += kt_map(
        "textColors",
        "Colours used for text; each one must reach [CONTRAST_MINIMUM] on every colour in [surfaces].",
        [(n, n) for n in contrast["text"]],
        "Color",
    )
    out.append("")
    out += kt_map("surfaces", "Surfaces text is drawn on.", [(n, n) for n in contrast["surfaces"]], "Color")
    out.append("")
    out += kt_map(
        "onFill",
        "Text colour on a filled control: name to (text, fill).",
        [(f"{t}/{f}", f"({t} to {f})") for t, f in contrast["onFill"].items()],
        "Pair<Color, Color>",
    )
    out.append("")
    out += kt_map(
        "onTint",
        "Text colour on a translucent tint, checked over every surface: name to (text, tint).",
        [(f"{t}/{f}", f"({t} to {f})") for t, f in contrast["onTint"].items()],
        "Pair<Color, Color>",
    )
    out += ["}", ""]
    out += [
        "/** Minimum WCAG contrast ratio for every text colour on every surface, in both themes. */",
        f"const val CONTRAST_MINIMUM = {contrast['minimum']}",
        "",
        "/** The two themes. */",
        "object FaiPalette {",
    ]
    for theme in ("dark", "light"):
        out += [f"{I4}val {theme} =", f"{I8}FaiColors("]
        out += [f"{I12}{n} = {kotlin_colour(themes[theme][n])}," for n in names]
        out += [f"{I8})"]
        if theme == "dark":
            out.append("")
    out += ["}", ""]

    space = dict(kit["space"])
    space_entries = [f"val {k} = {v}.dp" for k, v in space.items()]
    space_entries += [f"val s{v} = {v}.dp" for v in office["space"]["scale"]]
    out += kt_object("FaiSpace", "Spacing: kit names, then the shared scale (s2 .. s32).", space_entries)

    out += kt_object("FaiRadius", "Corner radii.", [f"val {k} = {v}.dp" for k, v in kit["radius"].items()])

    sizes = {k: v for k, v in kit["size"].items() if k not in office["drop"]["size"]}
    sizes.update(office["size"])
    out += kt_object("FaiSize", "Component sizes.", [f"val {k} = {v}.dp" for k, v in sizes.items()])

    bps = kit["breakpoints"]
    bp_entries = [
        f"val medium = {office['breakpoints']['medium']}.dp",
        f"val compact = {breakpoint_min(bps['compact'])}.dp",
        f"val desktop = {breakpoint_min(bps['desktop'])}.dp",
        f"val desktopShortHeight = {breakpoint_min(bps['desktopShortHeight'])}.dp",
        f"val phoneLandscapeHeight = {office['breakpoints']['phoneLandscapeHeight']}.dp",
    ]
    out += kt_object("FaiBreakpoint", "Lower bounds of the window width classes (DESIGN.md, layout).", bp_entries)

    alpha = office["alpha"]
    out += kt_object(
        "FaiAlpha",
        "Opacities.",
        [f"const val DISABLED = {alpha['disabled']}f", f"const val FILE_TINT = {alpha['fileTint']}f"],
    )

    motion = office["motion"]
    easing = ", ".join(f"{v}f" for v in motion["easing"])
    out += kt_object(
        "FaiMotion",
        "Durations and easing; reduced motion sets durations to 0.",
        [
            f"const val HOVER_MS = {motion['hoverMs']}",
            f"const val STATE_MS = {motion['stateMs']}",
            f"val easing = CubicBezierEasing({easing})",
        ],
    )

    sizes_sp = dict(kit["type"])
    for old, new in office["rename"]["type"].items():
        sizes_sp[new] = sizes_sp.pop(old)
    styles = office["typeStyle"]
    out += [
        "/** Text styles; font families come from the theme (IBM Plex Sans and Mono). */",
        "@Immutable",
        "class FaiTypography(",
        f"{I4}sans: FontFamily,",
        f"{I4}mono: FontFamily,",
        ") {",
    ]
    for name, st in styles.items():
        out += [
            f"{I4}val {name} =",
            f"{I8}TextStyle(",
            f"{I12}fontFamily = {st['font']},",
            f"{I12}fontSize = {sizes_sp[st['size']]}.sp,",
            f"{I12}fontWeight = FontWeight.{WEIGHTS[st['weight']]},",
            f"{I12}lineHeight = {st['lineHeight']}.sp,",
            f"{I8})",
            "",
        ]
    out += kt_map("all", "Every style by name, in token order (token preview, screenshots).", [(n, n) for n in styles], "TextStyle")
    out += ["}"]
    text = "\n".join(out) + "\n"

    report = []
    for theme in ("dark", "light"):
        pairs = sorted(contrast_pairs(themes[theme], contrast), key=lambda p: p[1])
        failing = [p for p in pairs if p[1] < contrast["minimum"]]
        report.append((theme, len(pairs), pairs[0], failing))
    return text, len(names), len(styles), report


def print_contrast(report):
    for theme, n_pairs, (label, lowest), failing in report:
        print(f"   {theme}: {n_pairs} contrast pairs, lowest {lowest:.2f} ({label})")
        for label, value in failing:
            print(f"   !! {theme}: {label} = {value:.2f}")


def main():
    check = "--check" in sys.argv[1:]
    kit = json.loads(KIT.read_text(encoding="utf-8"))
    office = json.loads(OFFICE.read_text(encoding="utf-8"))
    text, n_colours, n_styles, report = generate(kit, office)
    rel = OUT.relative_to(ROOT)
    print(f"== read {KIT.relative_to(ROOT)} (kit {kit['meta']['version']}) + {OFFICE.relative_to(ROOT)}")
    if check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"!! {rel} is out of date; run tools/tokens/gen_compose.py and commit the result. Difference:")
            diff = difflib.unified_diff(
                current.splitlines(), text.splitlines(), "committed", "generated", lineterm="", n=1
            )
            for line in list(diff)[:200]:
                print(f"   {line}")
            return 1
        print(f"== tokens: {rel} is up to date ({n_colours} colours x 2 themes, {n_styles} text styles)")
        print_contrast(report)
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"== wrote {rel}: {n_colours} colours x 2 themes, {n_styles} text styles")
    print_contrast(report)
    return 0


if __name__ == "__main__":
    sys.exit(main())
